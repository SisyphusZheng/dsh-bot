export function normalizeDesktopLanguage(value) {
  const language = String(value || '').trim().toLowerCase()
  if (language === 'en' || language.startsWith('en-')) return 'en'
  if (language === 'zh' || language.startsWith('zh-')) return 'zh-CN'
  return 'auto'
}

export function effectiveDesktopLanguage(value, systemLanguage = '') {
  const configured = normalizeDesktopLanguage(value)
  if (configured !== 'auto') return configured
  return /^zh(?:-|$)/i.test(String(systemLanguage || '')) ? 'zh-CN' : 'en'
}

export function desktopTranslator(language, systemLanguage = '') {
  const english = effectiveDesktopLanguage(language, systemLanguage) === 'en'
  return (text, params) => {
    const source = String(text ?? '')
    const translated = english ? (ENGLISH[source] ?? source) : source
    if (!params) return translated
    return translated.replace(/\{(\w+)\}/g, (match, key) => (
      key in params ? String(params[key]) : match
    ))
  }
}

